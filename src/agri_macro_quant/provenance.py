def stable_json_hash(value: Any) -> str:
    payload = json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        default=str,
        allow_nan=False,
    ).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def dataframe_hash(frame: pd.DataFrame) -> str:
    if frame is None:
        return stable_json_hash(None)
    hashed = pd.util.hash_pandas_object(frame, index=True).values.tobytes()
    if isinstance(frame.index, pd.MultiIndex):
        index_dtypes = [str(level.dtype) for level in frame.index.levels]
    else:
        index_dtypes = [str(frame.index.dtype)]
    schema = {
        "columns": [
            {"name": str(column), "dtype": str(dtype)}
            for column, dtype in zip(frame.columns, frame.dtypes, strict=True)
        ],
        "index_names": [str(name) if name is not None else None for name in frame.index.names],
        "index_dtypes": index_dtypes,
    }
    return hashlib.sha256(
        json.dumps(schema, sort_keys=True, separators=(",", ":")).encode("utf-8") + hashed
    ).hexdigest()


def file_hash(path: str | Path) -> str:
    """Return the SHA-256 digest of a file without loading it all at once."""

    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def source_tree_hash(project_root: str | Path) -> str:
    """Hash package source paths and bytes in a platform-independent order.

    Generated bytecode and cache directories are deliberately excluded.  The
    hash is useful even outside a Git checkout (for example, an unpacked source
    archive or a copied research directory).
    """

    root = Path(project_root).expanduser().resolve()
    source_root = root / "src"
    if not source_root.is_dir():
        source_root = Path(__file__).resolve().parents[1]

    excluded_directories = {"__pycache__", ".mypy_cache", ".pytest_cache", ".ruff_cache"}
    candidates = sorted(
        (
            path
            for path in source_root.rglob("*")
            if path.is_file()
            and not any(
                part in excluded_directories or part.endswith(".egg-info")
                for part in path.relative_to(source_root).parts
            )
            and path.name != ".DS_Store"
            and path.suffix not in {".pyc", ".pyo"}
        ),
        key=lambda path: path.relative_to(source_root).as_posix(),
    )
    digest = hashlib.sha256()
    for path in candidates:
        relative = path.relative_to(source_root).as_posix().encode("utf-8")
        digest.update(relative)
        digest.update(b"\0")
        with path.open("rb") as handle:
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(chunk)
        digest.update(b"\0")
    return digest.hexdigest()


def _git_metadata(project_root: Path) -> dict[str, Any]:
    try:
        inside = subprocess.run(
            ["git", "rev-parse", "--is-inside-work-tree"],
            cwd=project_root,
            check=True,
            capture_output=True,
            text=True,
            timeout=5,
        )
        if inside.stdout.strip().lower() != "true":
            raise subprocess.CalledProcessError(1, inside.args)
        revision = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=project_root,
            check=True,
            capture_output=True,
            text=True,
            timeout=5,
        ).stdout.strip()
        status = subprocess.run(
            ["git", "status", "--porcelain", "--untracked-files=normal"],
            cwd=project_root,
            check=True,
            capture_output=True,
            text=True,
            timeout=10,
        ).stdout
        return {"available": True, "commit": revision, "dirty": bool(status.strip())}
    except (OSError, subprocess.SubprocessError):
        return {"available": False, "commit": None, "dirty": None}


def _project_requirements(project_root: Path) -> list[str]:
    pyproject = project_root / "pyproject.toml"
    if pyproject.is_file() and tomllib is not None:
        try:
            parsed = tomllib.loads(pyproject.read_text(encoding="utf-8"))
            requirements = parsed.get("project", {}).get("dependencies", [])
            if isinstance(requirements, list):
                return [str(requirement) for requirement in requirements]
        except (OSError, ValueError):
            pass
    try:
        return list(importlib_metadata.requires("agri-macro-monitor") or [])
    except importlib_metadata.PackageNotFoundError:
        return []


def direct_dependency_versions(project_root: str | Path) -> dict[str, dict[str, str | None]]:
    """Return declared direct requirements and their installed versions."""

    result: dict[str, dict[str, str | None]] = {}
    for requirement in _project_requirements(Path(project_root).expanduser().resolve()):
        match = re.match(r"\s*([A-Za-z0-9][A-Za-z0-9._-]*)", requirement)
        if match is None:
            continue
        distribution = match.group(1)
        key = distribution.lower().replace("_", "-")
        try:
            installed = importlib_metadata.version(distribution)
        except importlib_metadata.PackageNotFoundError:
            installed = None
        result[key] = {"requirement": requirement, "installed_version": installed}
    return dict(sorted(result.items()))


def capture_reproducibility_state(project_root: str | Path) -> dict[str, Any]:
    """Capture code and runtime identity at the start of a run."""

    root = Path(project_root).expanduser().resolve()
    return {
        "source_tree_sha256": source_tree_hash(root),
        "git": _git_metadata(root),
        "python": platform.python_version(),
        "python_runtime": {
            "version": platform.python_version(),
            "implementation": platform.python_implementation(),
        },
        "direct_dependencies": direct_dependency_versions(root),
        "platform": platform.platform(),
    }


def build_manifest(
    *,
    project_root: str | Path,
    configuration: Mapping[str, Any],
    data: pd.DataFrame,
    as_of: Any,
    mode: str,
    seed: int,
    outputs: Mapping[str, Any] | None = None,
    raw_observations: pd.DataFrame | None = None,
    availability: pd.DataFrame | None = None,
    raw_snapshot_manifest: Mapping[str, Any] | None = None,
    raw_snapshot_manifest_sha256: str | None = None,
    raw_snapshot_manifest_path: str | None = None,
    upstream_snapshot_manifest: Mapping[str, Any] | None = None,
    upstream_snapshot_manifest_sha256: str | None = None,
    reproducibility_state: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    root = Path(project_root).resolve()
    state = dict(reproducibility_state or capture_reproducibility_state(root))
    source_sha = str(state["source_tree_sha256"])
    git = dict(state["git"])
    raw_frame_sha = dataframe_hash(raw_observations) if raw_observations is not None else None
    aligned_sha = dataframe_hash(data)
    availability_sha = dataframe_hash(availability) if availability is not None else None
    snapshot_file_sha = (
        str(raw_snapshot_manifest.get("sha256"))
        if raw_snapshot_manifest is not None and raw_snapshot_manifest.get("sha256")
        else None
    )
    semantic_configuration = dict(configuration)
    invocation = semantic_configuration.pop("invocation", {})
    return {
        "system_version": __version__,
        "source_tree_sha256": source_sha,
        "git": git,
        "git_commit": git["commit"],
        "git_dirty": git["dirty"],
        "code_revision": git["commit"] or f"source-tree:{source_sha}",
        "configuration_sha256": stable_json_hash(semantic_configuration),
        "invocation_sha256": stable_json_hash(invocation),
        "invocation": dict(invocation) if isinstance(invocation, Mapping) else {},
        "effective_runtime": dict(configuration.get("effective_runtime", {})),
        # Backward-compatible alias: historically this represented the aligned
        # market panel rather than the raw observation/vintage snapshot.
        "data_snapshot_sha256": aligned_sha,
        "raw_observation_vintage_sha256": raw_frame_sha,
        "raw_snapshot_file_sha256": snapshot_file_sha,
        "raw_snapshot_manifest_path": raw_snapshot_manifest_path,
        "raw_snapshot_manifest_sha256": raw_snapshot_manifest_sha256,
        "upstream_snapshot_manifest_sha256": upstream_snapshot_manifest_sha256,
        "upstream_snapshot_manifest_content_sha256": (
            stable_json_hash(upstream_snapshot_manifest)
            if upstream_snapshot_manifest
            else None
        ),
        "aligned_panel_sha256": aligned_sha,
        "aligned_availability_sha256": availability_sha,
        "as_of": pd.Timestamp(as_of).isoformat(),
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "mode": mode,
        "random_seed": int(seed),
        "python": state["python"],
        "python_runtime": state["python_runtime"],
        "direct_dependencies": state["direct_dependencies"],
        "platform": state["platform"],
        "rows": int(len(data)),
        "columns": list(map(str, data.columns)),
        "outputs": dict(outputs or {}),
    }


def write_manifest(path: str | Path, manifest: Mapping[str, Any]) -> Path:
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        json.dumps(
            dict(manifest),
            indent=2,
            sort_keys=True,
            default=str,
            allow_nan=False,
        ),
        encoding="utf-8",
    )
    return target
